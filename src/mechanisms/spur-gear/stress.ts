// ------------------------------------------------------------------ Tooth FE model

/**
 * 2D model of three teeth on a common rim sector (the loaded tooth in the middle). The neighbours give
 * the loaded tooth's root a realistic stiffness; the boundary (inner rim arc and the far sector sides)
 * is 1.5 pitches away from the loaded tooth.
 */
export interface ToothModel {
  mesh: Mesh2D;
  /** Angular pitch 2π/z. */
  pitch: number;
  /** Columns per pitch. */
  nc: number;
  /** Rim levels from rIn to rf (inclusive). */
  rimRadii: number[];
  /** Tooth levels from rf (index 0, shared with the rim) to ra. */
  toothRadii: number[];
  /** Half angle of a tooth at radius r ≥ rf (p/2 at the root land). */
  span(r: number): number;
  rimNode(i: number, c: number): number;
  toothNode(k: number, j: number, q: number): number;
  rIn: number;
  rf: number;
  flankStart: number;
  ra: number;
  /** Load application radius and direction (tooth frame, middle tooth axis along +x). */
  rLoad: number;
  loadDir: [number, number];
  /** FEM result for a unit normal force (1 N). */
  unit: FemResult;
  /** Max nodal von Mises stress in the root fillet of the loaded tooth, unit load. */
  rootMaxUnit: number;
  rootMaxNode: number;
  fixedNodes: number[];
  loadNodes: number[];
}

/** Builds and solves the 2D model for a unit normal force at radius `rLoad` on the middle tooth. */
export interface ToothMeshOptions {
  /** Columns per pitch. */
  nc?: number;
  /** Rows in the root fillet. */
  nFillet?: number;
  /** Rows on the involute flank. */
  nFlank?: number;
}

export function buildToothModel(m: number, z: number, x: number, b: number, rLoad: number, opts: ToothMeshOptions = {}): ToothModel {
  const g = gearDims(m, z, ALPHA, x);
  const rp = g.d / 2;
  const rb = g.db / 2;
  const ra = g.da / 2;
  const rf = g.df / 2;
  const p = (2 * Math.PI) / z;
  const psiP = g.s / (2 * rp);
  const psi = (r: number): number => psiP + inv(g.alpha) - inv(Math.acos(Math.min(1, rb / Math.max(r, rb))));
  // True root geometry: the trochoidal fillet generated by the rack tip rounding (incl. undercut).
  const fillet = rootFillet(m, z, x, ALPHA);
  const rIn = rf - 2.5 * m;
  // Form circle: the straight flank of the rack ends at depth h_FfP = 1.25·m − ρ·(1 − sin α) below its
  // reference line; along the line of action this gives the lowest generated involute point.
  const rhoA = 0.38 * m;
  const hFfP = 1.25 * m - rhoA * (1 - Math.sin(g.alpha));
  const rollForm = rb * Math.tan(g.alpha) - (hFfP - x * m) / Math.sin(g.alpha);
  const rForm = rollForm > 0 ? Math.hypot(rb, rollForm) : rb; // ≤ 0: undercut, the involute starts at rb
  const flankStart = Math.min(Math.max(rForm, rf + 0.05 * m), ra - 0.5 * m);
  const span = (r: number): number => {
    if (r <= rf) return p / 2;
    // Below the form circle only the fillet exists; above it the involute, unless the fillet cuts
    // into it (undercut).
    const fil = fillet.halfAngle(r);
    const h = r < flankStart ? fil : Math.min(psi(r), fil);
    return Math.min(p / 2, Number.isFinite(h) ? h : psi(Math.max(r, rb)));
  };

  const nc = opts.nc ?? 20;
  const nRim = 7;
  const rimRadii: number[] = [];
  for (let i = 0; i <= nRim; i++) rimRadii.push(rIn + ((rf - rIn) * i) / nRim);
  const toothRadii: number[] = [rf];
  const nF = opts.nFillet ?? 12;
  for (let i = 1; i <= nF; i++) toothRadii.push(rf + (flankStart - rf) * (i / nF) ** 1.15); // denser near the root
  const nFl = opts.nFlank ?? 16;
  for (let i = 1; i <= nFl; i++) toothRadii.push(flankStart + ((ra - flankStart) * i) / nFl);
  const nT = toothRadii.length - 1;

  const rimCols = 3 * nc + 1;
  const rimCount = (nRim + 1) * rimCols;
  const rimNode = (i: number, c: number): number => i * rimCols + c;
  const toothNode = (k: number, j: number, q: number): number =>
    j === 0 ? rimNode(nRim, k * nc + q) : rimCount + (k * nT + (j - 1)) * (nc + 1) + q;
  const nNodes = rimCount + 3 * nT * (nc + 1);
  const x0 = new Float64Array(nNodes);
  const y0 = new Float64Array(nNodes);
  const put = (n: number, r: number, th: number): void => {
    x0[n] = r * Math.cos(th);
    y0[n] = r * Math.sin(th);
  };
  for (let i = 0; i <= nRim; i++) {
    for (let c = 0; c < rimCols; c++) put(rimNode(i, c), rimRadii[i], (c / (3 * nc) - 0.5) * 3 * p);
  }
  for (let k = 0; k < 3; k++) {
    for (let j = 1; j <= nT; j++) {
      const r = toothRadii[j];
      const sp = span(r);
      for (let q = 0; q <= nc; q++) put(toothNode(k, j, q), r, (k - 1) * p + (-1 + (2 * q) / nc) * sp);
    }
  }
  const tris: number[] = [];
  const quad = (n0: number, n1: number, n2: number, n3: number, flip: boolean): void => {
    // n0–n1 inner edge, n2–n3 outer edge.
    if (flip) tris.push(n0, n1, n3, n0, n3, n2);
    else tris.push(n0, n1, n2, n1, n3, n2);
  };
  for (let i = 0; i < nRim; i++) {
    for (let c = 0; c < 3 * nc; c++) quad(rimNode(i, c), rimNode(i, c + 1), rimNode(i + 1, c), rimNode(i + 1, c + 1), (i + c) % 2 === 0);
  }
  for (let k = 0; k < 3; k++) {
    for (let j = 0; j < nT; j++) {
      for (let q = 0; q < nc; q++) {
        quad(toothNode(k, j, q), toothNode(k, j, q + 1), toothNode(k, j + 1, q), toothNode(k, j + 1, q + 1), (j + q) % 2 === 0);
      }
    }
  }
  const mesh: Mesh2D = { x: x0, y: y0, tri: Int32Array.from(tris) };

  // Boundary: inner rim arc and the far sides of the sector (1.5 pitches from the loaded tooth).
  const fixedNodes: number[] = [];
  for (let c = 0; c < rimCols; c++) fixedNodes.push(rimNode(0, c));
  for (let i = 1; i <= nRim; i++) fixedNodes.push(rimNode(i, 0), rimNode(i, 3 * nc));
  const fixedDofs = fixedNodes.flatMap((n) => [2 * n, 2 * n + 1]);

  // Load: unit normal force on the +θ flank of the middle tooth at rLoad, along the line of action.
  const rL = Math.min(ra - 0.05 * m, Math.max(flankStart, rLoad));
  const t = Math.sqrt(Math.max(0, (rL / rb) ** 2 - 1));
  const uT = psiP + inv(g.alpha) - t;
  const loadDir: [number, number] = [Math.sin(uT), -Math.cos(uT)];
  const load = new Float64Array(nNodes * 2);
  let jL = 0;
  while (jL < nT - 1 && toothRadii[jL + 1] < rL) jL++;
  const f = Math.min(1, Math.max(0, (rL - toothRadii[jL]) / (toothRadii[jL + 1] - toothRadii[jL])));
  const nA = toothNode(1, jL, nc);
  const nB = toothNode(1, jL + 1, nc);
  load[2 * nA] += loadDir[0] * (1 - f);
  load[2 * nA + 1] += loadDir[1] * (1 - f);
  load[2 * nB] += loadDir[0] * f;
  load[2 * nB + 1] += loadDir[1] * f;

  const unit = solvePlaneStress(mesh, { E: E_STEEL, nu: NU, t: b }, fixedDofs, load);

  // Root of the loaded tooth: fillets on both sides and the adjoining root lands, excluding the
  // neighbourhood of the point load (a point force is a singularity in FEM; contact is checked by Hertz).
  const rootTop = flankStart + 0.25 * m;
  const lx = (x0[nA] + x0[nB]) / 2;
  const ly = (y0[nA] + y0[nB]) / 2;
  const fixedSet = new Set(fixedNodes);
  let rootMaxUnit = 0;
  let rootMaxNode = 0;
  const consider = (n: number): void => {
    if (fixedSet.has(n) || Math.hypot(x0[n] - lx, y0[n] - ly) < 1.2 * m) return;
    if (unit.nodalVm[n] > rootMaxUnit) {
      rootMaxUnit = unit.nodalVm[n];
      rootMaxNode = n;
    }
  };
  for (let c = Math.round(nc / 2); c <= Math.round(2.5 * nc); c++) consider(rimNode(nRim, c));
  for (let j = 1; j <= nT && toothRadii[j] <= rootTop; j++) for (let q = 0; q <= nc; q++) consider(toothNode(1, j, q));

  return {
    mesh,
    pitch: p,
    nc,
    rimRadii,
    toothRadii,
    span,
    rimNode,
    toothNode,
    rIn,
    rf,
    flankStart,
    ra,
    rLoad: rL,
    loadDir,
    unit,
    rootMaxUnit,
    rootMaxNode,
    fixedNodes,
    loadNodes: [nA, nB],
  };
}

/**
 * Nodal von Mises stress (unit load) at polar position (r, Δθ) relative to the loaded tooth,
 * bilinear on the structured mesh. Returns null outside the modelled sector (|Δθ| > 1.5 pitches or r < rIn).
 */
export function sampleTooth(tm: ToothModel, r: number, dth: number): number | null {
  const p = tm.pitch;
  if (Math.abs(dth) > 1.5 * p || r < tm.rIn) return null;
  const v = tm.unit.nodalVm;
  const lerp = (a: number, b: number, f: number): number => a + (b - a) * f;
  const bracket = (R: number[], val: number): [number, number] => {
    const rc = Math.min(R[R.length - 1], Math.max(R[0], val));
    let i = 0;
    while (i < R.length - 2 && R[i + 1] < rc) i++;
    return [i, Math.min(1, Math.max(0, (rc - R[i]) / (R[i + 1] - R[i])))];
  };
  if (r < tm.rf) {
    const [i, fi] = bracket(tm.rimRadii, r);
    const cf = Math.min(3 * tm.nc, Math.max(0, (dth / (3 * p) + 0.5) * 3 * tm.nc));
    const c = Math.min(3 * tm.nc - 1, Math.floor(cf));
    const fc = cf - c;
    const row = (ii: number): number => lerp(v[tm.rimNode(ii, c)], v[tm.rimNode(ii, c + 1)], fc);
    return lerp(row(i), row(i + 1), fi);
  }
  const k = Math.min(2, Math.max(0, Math.round(dth / p) + 1));
  const local = dth - (k - 1) * p;
  const [j, fj] = bracket(tm.toothRadii, r);
  const rc = Math.min(tm.ra, Math.max(tm.rf, r));
  const u = Math.min(1, Math.max(-1, local / tm.span(rc)));
  const qf = ((u + 1) / 2) * tm.nc;
  const q = Math.min(tm.nc - 1, Math.floor(qf));
  const fq = qf - q;
  const row = (jj: number): number => lerp(v[tm.toothNode(k, jj, q)], v[tm.toothNode(k, jj, q + 1)], fq);
  return lerp(row(j), row(j + 1), fj);
}

/**
 * ISO 6336-3, method B: tooth form factor Y_F and stress correction factor Y_S for a load at the outer
 * point of single tooth contact (spur gear, standard rack h_fP = 1.25·m, ρ_fP = 0.38·m).
 */
export function iso6336YFYS(m: number, z: number, x: number, epsAlpha: number, alphaDeg = 20): { YF: number; YS: number } {
  const an = deg(alphaDeg);
  const hfP = 1.25;
  const rhofP = 0.38;
  const E = Math.PI / 4 - hfP * Math.tan(an) - ((1 - Math.sin(an)) * rhofP) / Math.cos(an);
  const G = rhofP - hfP + x;
  const H = (2 / z) * (Math.PI / 2 - E) - Math.PI / 3;
  let th = Math.PI / 6;
  for (let i = 0; i < 60; i++) th = ((2 * G) / z) * Math.tan(th) - H;
  const sFn = z * Math.sin(Math.PI / 3 - th) + Math.sqrt(3) * (G / Math.cos(th) - rhofP);
  const rhoF = rhofP + (2 * G * G) / (Math.cos(th) * (z * Math.cos(th) ** 2 - 2 * G));
  const d = m * z;
  const db = d * Math.cos(an);
  const da = d + 2 * m * (1 + x);
  const den = 2 * Math.sqrt((Math.sqrt((da / 2) ** 2 - (db / 2) ** 2) - ((Math.PI * d * Math.cos(an)) / z) * (epsAlpha - 1)) ** 2 + (db / 2) ** 2);
  const aen = Math.acos(db / den);
  const ge = (Math.PI / 2 + 2 * x * Math.tan(an)) / z + inv(an) - inv(aen);
  const aFen = aen - ge;
  const hFe = 0.5 * ((Math.cos(ge) - Math.sin(ge) * Math.tan(aFen)) * (den / m) - z * Math.cos(Math.PI / 3 - th) - G / Math.cos(th) + rhofP);
  const YF = (6 * hFe * Math.cos(aFen)) / (sFn * sFn * Math.cos(an));
  const L = sFn / hFe;
  const qs = sFn / (2 * rhoF);
  const YS = (1.2 + 0.13 * L) * qs ** (1 / (1.21 + 2.3 / L));
  return { YF, YS };
}

const wrap = (a: number): number => Math.atan2(Math.sin(a), Math.cos(a));

/** Centre angle (body frame) of the tooth closest to `target`. */
function loadedToothCentre(phase: number, z: number, target: number): number {
  const step = (2 * Math.PI) / z;
  const k = Math.round(wrap(target - phase) / step);
  return phase + k * step;
}

// ------------------------------------------------------------------ Shafts

interface ShaftSpec {
  segs: { z0: number; z1: number; r: number }[];
  zA: number;
  zB: number;
  RA: number;
  RB: number;
  /** Unit direction of the gear force acting on this shaft (body frame). */
  dir: [number, number];
  torque(z: number): number;
  shoulders: number[];
  keyway: { z0: number; z1: number };
}

function shaftRadius(s: ShaftSpec, z: number): number {
  for (const seg of s.segs) if (z >= seg.z0 - 1e-6 && z <= seg.z1 + 1e-6) return seg.r;
  return s.segs[0].r;
}

function shaftStress(s: ShaftSpec, p: Vec3, keyAngle: number): number {
  const [x, y, z] = p;
  const r = shaftRadius(s, z);
  const rho = Math.min(r, Math.hypot(x, y));
  const d = 2 * r;
  let M = 0;
  if (z >= s.zA && z <= 0) M = s.RA * (z - s.zA);
  else if (z > 0 && z <= s.zB) M = s.RB * (s.zB - z);
  const I = (Math.PI * d ** 4) / 64;
  const J = 2 * I;
  // Tension on the side the load points to.
  const along = rho > 1e-6 ? (x * s.dir[0] + y * s.dir[1]) / Math.hypot(x, y) : 0;
  let sb = (M * rho * along) / I;
  let tau = (s.torque(z) * rho) / J;
  // Stress concentration: shoulder fillets and the keyway.
  let kb = 1;
  for (const zs of s.shoulders) kb = Math.max(kb, 1 + 1.0 * Math.exp(-(((z - zs) / 1.2) ** 2)));
  if (z >= s.keyway.z0 - 1 && z <= s.keyway.z1 + 1) {
    const dAng = Math.abs(wrap(Math.atan2(y, x) - keyAngle));
    kb = Math.max(kb, dAng < 0.6 ? 2.0 : 1.3);
  }
  const kt = 1 + 0.7 * (kb - 1);
  sb *= kb;
  tau *= kt;
  return Math.sqrt(sb * sb + 3 * tau * tau);
}

// ------------------------------------------------------------------ Bearings (Hamrock–Brewe)

/** Max contact pressure (MPa) of a ball on the inner raceway for ball load Q (N). */
export function ballContactPressure(Q: number, Dw: number, dm: number, conformity = 0.52, race: 'inner' | 'outer' = 'inner'): number {
  if (Q <= 0) return 0;
  // Rolling direction: convex inner raceway adds curvature, the concave outer raceway removes it.
  const Rx = race === 'inner' ? 1 / (2 / Dw + 2 / (dm - Dw)) : 1 / (2 / Dw - 2 / (dm + Dw));
  const Ry = 1 / (2 / Dw - 1 / (conformity * Dw));
  const Ep = E_STEEL / (1 - NU * NU);
  const kk = 1.0339 * (Ry / Rx) ** 0.636;
  const Ek = 1.0003 + (0.5968 * Rx) / Ry;
  const Rp = 1 / (1 / Rx + 1 / Ry);
  const Dy = 2 * ((6 * kk * kk * Ek * Q * Rp) / (Math.PI * Ep)) ** (1 / 3);
  const Dx = 2 * ((6 * Ek * Q * Rp) / (Math.PI * kk * Ep)) ** (1 / 3);
  return (6 * Q) / (Math.PI * Dx * Dy);
}

function bearingField(R: number, brg: { d: number; D: number; n: number; ball: number }, dir: [number, number], zc: number): (p: Vec3) => number {
  const Qmax = (5 * R) / brg.n; // Stribeck
  const dm = (brg.d + brg.D) / 2;
  return ([x, y, z]) => {
    if (Math.abs(z - zc) > 20) return 0;
    const ang = Math.atan2(y, x) - Math.atan2(dir[1], dir[0]);
    const c = Math.cos(ang);
    if (c <= 0) return 0;
    // Outer ring (beyond the ball circle) has the lower, concave-raceway pressure; balls carry the higher one.
    const race = Math.hypot(x, y) > dm / 2 + 0.3 * brg.ball ? 'outer' : 'inner';
    return ballContactPressure(Qmax * c ** 1.5, brg.ball, dm, 0.52, race);
  };
}

// ------------------------------------------------------------------ Plot of the tooth FE mesh

function toothPlot(label: string, tm: ToothModel, scale: number): StressPlot {
  return {
    label: { bg: label },
    draw(ctx, w, h, colour) {
      const { x, y, tri } = tm.mesh;
      // Tooth pointing up: screen X = −y, screen Y = −x.
      let minX = Infinity;
      let maxX = -Infinity;
      let minY = Infinity;
      let maxY = -Infinity;
      for (let i = 0; i < x.length; i++) {
        minX = Math.min(minX, -y[i]);
        maxX = Math.max(maxX, -y[i]);
        minY = Math.min(minY, -x[i]);
        maxY = Math.max(maxY, -x[i]);
      }
      const pad = 26;
      const s = Math.min((w - 2 * pad) / (maxX - minX), (h - 2 * pad) / (maxY - minY));
      const ox = (w - (maxX - minX) * s) / 2 - minX * s;
      const oy = (h - (maxY - minY) * s) / 2 - minY * s;
      const P = (n: number): [number, number] => [ox + -y[n] * s, oy + -x[n] * s];
      ctx.clearRect(0, 0, w, h);
      ctx.lineWidth = 0.4;
      // Own scale: red slightly above the root maximum, so the gradient in the tooth is visible
      // (the elements under the point load saturate, as expected).
      const top = tm.rootMaxUnit * 1.15;
      for (let e = 0; e < tri.length / 3; e++) {
        const [a, b, c] = [tri[3 * e], tri[3 * e + 1], tri[3 * e + 2]];
        ctx.beginPath();
        ctx.moveTo(...P(a));
        ctx.lineTo(...P(b));
        ctx.lineTo(...P(c));
        ctx.closePath();
        ctx.fillStyle = colour(Math.min(1, tm.unit.vm[e] / top));
        ctx.fill();
        ctx.strokeStyle = 'rgba(0,0,0,0.16)';
        ctx.stroke();
      }
      // Fixed boundary marks.
      ctx.fillStyle = '#9aa6b2';
      for (const n of tm.fixedNodes) {
        const [px, py] = P(n);
        ctx.fillRect(px - 2, py - 2, 4, 4);
      }
      // Load arrow (pointing along the force, ending at the flank).
      const [lx, ly] = P(tm.loadNodes[0]);
      const dx = -tm.loadDir[1];
      const dy = -tm.loadDir[0];
      const len = 46;
      ctx.strokeStyle = '#ffffff';
      ctx.fillStyle = '#ffffff';
      ctx.lineWidth = 2.5;
      ctx.beginPath();
      ctx.moveTo(lx - dx * len, ly - dy * len);
      ctx.lineTo(lx - dx * 6, ly - dy * 6);
      ctx.stroke();
      ctx.beginPath();
      ctx.moveTo(lx, ly);
      ctx.lineTo(lx - dx * 11 - dy * 5, ly - dy * 11 + dx * 5);
      ctx.lineTo(lx - dx * 11 + dy * 5, ly - dy * 11 - dx * 5);
      ctx.closePath();
      ctx.fill();
      ctx.font = '600 13px system-ui, sans-serif';
      ctx.fillText('Fₙ', lx - dx * len - 8, ly - dy * len - 6);
      // Max root stress marker.
      const [mx, my] = P(tm.rootMaxNode);
      ctx.strokeStyle = '#ffffff';
      ctx.lineWidth = 2;
      ctx.beginPath();
      ctx.arc(mx, my, 7, 0, Math.PI * 2);
      ctx.stroke();
      ctx.fillText(`σmax = ${Math.round(tm.rootMaxUnit * scale)} MPa`, Math.min(w - 120, mx + 10), my + 4);
    },
  };
}

